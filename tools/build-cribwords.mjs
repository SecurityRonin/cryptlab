// Regenerates web/cribwords.js from SCOWL — the crib tool's dictionary.
//   curl -L -o /tmp/scowl.tar.gz https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz
//   tar xzf /tmp/scowl.tar.gz -C /tmp && node tools/build-cribwords.mjs /tmp/scowl-2020.12.07
// Size 20 and below: the ~11k commonest words. Measured on the 20 challenges it
// holds 88% of their words (size 35 adds 6 points for four times the bytes).
import fs from 'fs';
import path from 'path';
const root = process.argv[2];
if (!root) throw new Error('usage: node tools/build-cribwords.mjs <unpacked scowl-2020.12.07 dir>');
const words = new Set();
for (const size of [10, 20]) for (const v of ['english', 'american']) {
    const f = path.join(root, 'final', `${v}-words.${size}`);
    const lines = fs.readFileSync(f, 'latin1').split('\n');   // american-words.* hold only US spellings, so may be tiny
    // lowercase-only drops proper nouns; [a-z] drops possessives and accented forms
    for (const l of lines) if (/^[a-z]{2,}$/.test(l)) words.add(l.toUpperCase());
}
if (words.size < 5000) throw new Error(`only ${words.size} words — is ${root} an unpacked SCOWL release?`);
const full = fs.readFileSync(path.join(root, 'Copyright'), 'latin1');
fs.writeFileSync('web/cribwords-COPYRIGHT.txt', full);          // the complete notice, verbatim
const notice = full.slice(0, full.indexOf('"as is" without express or implied warranty.') + 45).trim();
const out = `/* Crib dictionary: SCOWL 2020.12.07, sizes 10 and 20, English + American,
   lowercase-only words of two letters or more. Generated by tools/build-cribwords.mjs;
   source scowl-2020.12.07.tar.gz, sha256 5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc.
   Full notice, including the sources' own terms: cribwords-COPYRIGHT.txt

${notice.split('\n').map((l) => '   ' + l).join('\n').trimEnd()}
*/
self.CRIB_DICT=${JSON.stringify([...words].sort().join(' '))};
`;
fs.writeFileSync('web/cribwords.js', out);
console.log(`web/cribwords.js: ${words.size} words, ${out.length} bytes`);
